"use client"

// shadcn's Sidebar, trimmed for a desktop app whose Session keeps the
// sidebar's state:
// - no cookie: `SidebarProvider` is controlled, and `src/shell/use-sidebar.ts`
//   keeps whether it is open and how wide it is in the Session;
// - no ⌘B: `src/shell/app-command-manifest.json` owns every shortcut, and the
//   sidebar's is ⌘[ there;
// - no mobile Sheet and no `use-mobile`: Plumo is desktop only;
// - no `TooltipProvider` of its own: the one in main.tsx sets the delay for
//   every tooltip, the sidebar's included;
// - no `SidebarRail`: the sidebar's edge resizes it (Plumo's handle, in
//   `src/shell/sidebar.tsx`) instead of toggling it;
// - no `SidebarMenuSkeleton`: nothing in Plumo loads slowly enough to show one.
// The container sits in the flow and slides out by its left margin, where
// shadcn's is fixed over a gap that shrinks, so one element carries the
// width: the edge drag sets `--sidebar-width` on it alone. The slide is
// `sidebar-slide`, which runs only on a toggle and shares its curve with the
// tab bar. A current item is `sidebar-selected`, not the hover fill
// (ADR-0012).
// The groups, labels, menus and rows take Plumo's values under shadcn's
// names: the sidebar pads its column once, so a group adds no padding of its
// own; a label is 28px and its icon is the group's fold caret; a row is the
// 32px row described at `sidebarMenuButtonVariants`.

